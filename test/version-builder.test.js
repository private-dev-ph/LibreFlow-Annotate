const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');
const AdmZip = require('adm-zip');

test('project version builder exports processed training data without touching source data or augmenting evaluation splits', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'libreflow-version-builder-'));
  const data = path.join(dir, 'data'), uploads = path.join(dir, 'uploads'), versions = path.join(dir, 'versions');
  [data, uploads, versions].forEach(folder => fs.mkdirSync(folder));
  process.env.LIBREFLOW_DATA_DIR = data;
  process.env.LIBREFLOW_UPLOADS_DIR = uploads;
  process.env.LIBREFLOW_DATASETS_DIR = path.join(dir, 'datasets');
  process.env.LIBREFLOW_VERSIONS_DIR = versions;
  const write = (file, value) => fs.writeFileSync(path.join(data, file), JSON.stringify(value));
  const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
  const images = [], annotations = [];
  for (let i = 0; i < 6; i++) {
    const filename = `source-${i}.png`, buffer = Buffer.alloc(64 * 48 * 3);
    for (let y = 0; y < 48; y++) for (let x = 0; x < 64; x++) {
      const offset = (y * 64 + x) * 3;
      buffer[offset] = x * 3; buffer[offset + 1] = y * 4; buffer[offset + 2] = i * 35;
    }
    await sharp(buffer, { raw: { width: 64, height: 48, channels: 3 } }).png().toFile(path.join(uploads, filename));
    images.push({ id: `image-${i}`, filename, originalName: filename, projectId: 'project', width: 64, height: 48, annotated: i < 5, isNull: i === 4, tags: ['inspection'] });
    if (i < 4) annotations.push({ id: `box-${i}`, imageId: `image-${i}`, label: 'old', type: 'bbox', data: { x: 8, y: 6, width: 16, height: 12 } });
  }
  fs.copyFileSync(path.join(uploads, 'source-0.png'), path.join(uploads, 'duplicate.png'));
  images.push({ ...images[0], id: 'duplicate', filename: 'duplicate.png', originalName: 'duplicate.png' });
  annotations.push({ ...annotations[0], id: 'duplicate-box', imageId: 'duplicate' });
  write('projects.json', [{ id: 'project', userId: 'owner', name: 'Version test', labelClasses: [{ name: 'old' }] }]);
  write('images.json', images); write('annotations.json', annotations);
  for (const file of ['datasets.json', 'dataset_versions.json', 'reviews.json']) write(file, []);
  const originalIndex = hash(path.join(data, 'images.json')), originalAnnotations = hash(path.join(data, 'annotations.json'));
  const imageHashes = images.map(image => hash(path.join(uploads, image.filename)));
  const express = require('express'), app = express();
  app.use(express.json());
  app.use((req, res, next) => { req.session = { userId: req.get('x-user') || 'owner', username: 'Fixture' }; next(); });
  app.use('/api/dataset-lifecycle', require('../routes/dataset-lifecycle'));
  const server = await new Promise(resolve => { const listener = app.listen(0, '127.0.0.1', () => resolve(listener)); });
  t.after(async () => {
    await new Promise(resolve => server.close(resolve));
    assert.ok(path.resolve(dir).startsWith(path.resolve(os.tmpdir()) + path.sep));
    fs.rmSync(dir, { recursive: true, force: true });
  });
  const base = `http://127.0.0.1:${server.address().port}/api/dataset-lifecycle/project/project`;
  const post = (suffix, body) => fetch(base + suffix, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const options = { name: 'Processed', selection: 'annotated', splitRatios: { train: 60, valid: 20, test: 20 }, seed: 'test-split', preserveExistingSplits: false,
    processing: { preprocessing: { autoOrient: true, resize: { enabled: true, mode: 'stretch', width: 32, height: 32 }, modifyClasses: { old: 'component' } },
      augmentation: { count: 2, seed: 'fixed', horizontalFlip: 1, brightness: { enabled: true, mode: 'additive', min: 5, max: 5 } } } };
  const previewResponse = await post('/versions/preview', options), preview = await previewResponse.json();
  assert.equal(previewResponse.status, 200, JSON.stringify(preview));
  assert.equal(preview.selection.selected, 6);
  assert.equal(preview.selection.excludedUnfinished, 1);
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(data, 'dataset_versions.json'))), []);
  const createdResponse = await post('/versions', options), created = await createdResponse.json();
  assert.equal(createdResponse.status, 201, JSON.stringify(created));
  const manifest = await (await fetch(`${base}/versions/${created.id}`)).json();
  assert.equal(manifest.integrityValid, true);
  assert.equal(manifest.classes[0].name, 'component');
  assert.equal(manifest.stats.sourceImages, 6);
  assert.ok(manifest.stats.augmentationVariants > 0);
  assert.ok(manifest.stats.duplicateVariantsSkipped > 0);
  assert.ok(manifest.images.every(image => image.width === 32 && image.height === 32));
  assert.ok(!manifest.images.some(image => image.sourceImageId === 'image-5'));
  assert.ok(manifest.images.filter(image => image.lineage.variant.startsWith('augmentation')).every(image => image.split === 'train'));
  assert.equal(manifest.images.find(image => image.id === 'image-0').split, manifest.images.find(image => image.id === 'duplicate').split);
  assert.deepEqual(manifest.splits.sourceCounts, preview.splits.counts);
  assert.deepEqual(manifest.annotations.find(annotation => annotation.imageId === 'image-0').data, { x: 4, y: 4, width: 8, height: 8 });
  const download = await fetch(`${base}/versions/${created.id}/download`);
  assert.equal(download.status, 200);
  const zip = new AdmZip(Buffer.from(await download.arrayBuffer()));
  assert.ok(zip.getEntry('data.yaml')); assert.ok(zip.getEntry('annotations/coco.json')); assert.ok(zip.getEntry('checksums.sha256'));
  const exportedImages = zip.getEntries().filter(entry => entry.entryName.startsWith('training/') && entry.entryName.includes('/images/'));
  assert.equal(exportedImages.length, manifest.images.length);
  const exportedPixels = await sharp(exportedImages[0].getData()).metadata();
  assert.deepEqual([exportedPixels.width, exportedPixels.height], [32, 32]);
  assert.equal(hash(path.join(data, 'images.json')), originalIndex);
  assert.equal(hash(path.join(data, 'annotations.json')), originalAnnotations);
  assert.deepEqual(images.map(image => hash(path.join(uploads, image.filename))), imageHashes);
  const denied = await fetch(`${base}/versions/${created.id}/download`, { headers: { 'x-user': 'outsider' } });
  assert.equal(denied.status, 403);
  const isolatedResponse = await post('/versions', { ...options, name: 'Classification', processing: { preprocessing: { isolateObjects: true }, augmentation: { count: 0 } } });
  const isolated = await isolatedResponse.json();
  assert.equal(isolatedResponse.status, 201, JSON.stringify(isolated));
  assert.equal(isolated.stats.images, 5);
  const classZip = new AdmZip(Buffer.from(await (await fetch(`${base}/versions/${isolated.id}/download`)).arrayBuffer()));
  assert.equal(classZip.getEntries().filter(entry => /^classification\/(train|valid|test)\/[^/]+\/.*\.png$/.test(entry.entryName)).length, 5);
  assert.ok(classZip.getEntry('classification/classes.json'));

  const unnamedResponse = await post('/versions', { name: '   ', selection: 'all', processing: { preprocessing: { autoOrient: true } } });
  const unnamed = await unnamedResponse.json();
  assert.equal(unnamedResponse.status, 201, JSON.stringify(unnamed));
  assert.match(unnamed.name, /^Version \d+$/);
  assert.equal(unnamed.stats.sourceImages, 7);
  const expandedManifest = await (await fetch(`${base}/versions/${unnamed.id}`)).json();
  assert.equal(expandedManifest.images.find(image => image.id === 'image-4').isExplicitNull, true);
  assert.equal(expandedManifest.images.find(image => image.id === 'image-5').isExplicitNull, false);
  const selectedZip = new AdmZip(Buffer.from(await (await fetch(`${base}/versions/${unnamed.id}/download?format=csv&images=false&includeNull=false`)).arrayBuffer()));
  const exportedSubset = JSON.parse(selectedZip.readAsText('export-manifest.json'));
  assert.equal(exportedSubset.images.length, 6);
  assert.ok(!exportedSubset.images.some(image => image.id === 'image-5'));
  assert.ok(selectedZip.getEntry('annotations.csv'));
  assert.ok(!selectedZip.getEntries().some(entry => /\.(png|jpe?g|webp)$/i.test(entry.entryName)));
  assert.equal((await fetch(`${base}/versions/${unnamed.id}/download?format=invalid`)).status, 400);

  const versionIndexBefore = hash(path.join(data, 'dataset_versions.json'));
  const sampleResponse = await post('/versions/sample-preview', { operation: 'preprocessing.resize', processing: options.processing });
  const sample = await sampleResponse.json();
  assert.equal(sampleResponse.status, 200, JSON.stringify(sample));
  assert.equal(sample.sample.id, 'image-0');
  assert.equal(sample.after[0].width, 32);
  assert.equal(sample.after[0].height, 32);
  assert.match(sample.before.dataUrl, /^data:image\/png;base64,/);
  assert.equal(hash(path.join(data, 'dataset_versions.json')), versionIndexBefore);
  assert.equal((await post('/versions/sample-preview', { operation: 'invalid' })).status, 400);
  assert.equal((await fetch(`${base}/versions/sample-preview`, { method: 'POST', headers: { 'x-user': 'outsider', 'Content-Type': 'application/json' }, body: JSON.stringify({ operation: 'preprocessing.resize' }) })).status, 403);
  assert.equal(hash(path.join(data, 'images.json')), originalIndex);
  assert.equal(hash(path.join(data, 'annotations.json')), originalAnnotations);
  assert.deepEqual(images.map(image => hash(path.join(uploads, image.filename))), imageHashes);
});
